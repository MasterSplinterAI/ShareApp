const { renderEmailLayout } = require('./layout');
const { escapeHtml, nl2br } = require('./escape');

function formatMarkdownPreviewHtml(md) {
  if (!md) return '';
  const lines = String(md).split('\n').slice(0, 60);
  const htmlLines = lines.map((rawLine) => {
    const line = rawLine.trimEnd();
    if (!line.trim()) return '<div style="height:8px;"></div>';
    if (/^#{1,3}\s+/.test(line)) {
      const heading = escapeHtml(line.replace(/^#{1,3}\s+/, ''));
      return `<p style="margin:12px 0 4px;font-size:14px;font-weight:700;color:#0f172a;">${heading}</p>`;
    }
    if (/^[-*•]\s+/.test(line)) {
      const item = escapeHtml(line.replace(/^[-*•]\s+/, '')).replace(
        /\*\*(.+?)\*\*/g,
        '<strong>$1</strong>'
      );
      return `<p style="margin:3px 0 3px 12px;font-size:14px;line-height:1.55;color:#334155;">• ${item}</p>`;
    }
    const formatted = escapeHtml(line).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
    return `<p style="margin:4px 0;font-size:14px;line-height:1.6;color:#334155;">${formatted}</p>`;
  });
  return htmlLines.join('\n');
}

function renderTranscriptReport({
  meetingTitle,
  label,
  orgName,
  summaryExcerpt,
  senderName,
  personalNote,
  transcriptPreview,
  includeTranscript,
}) {
  const title = meetingTitle || 'Call / Meeting';
  const reportLabel = label || 'AI Insights Report';
  const subject = `${reportLabel}: ${title} — Lalia`;

  const textParts = [
    `${senderName ? `${senderName} shared the` : 'Attached is the'} ${reportLabel.toLowerCase()} for "${title}"${orgName ? ` (${orgName})` : ''}, generated by Lalia.`,
  ];
  if (personalNote && String(personalNote).trim()) {
    textParts.push('', `Note from ${senderName || 'host'}:\n"${String(personalNote).trim()}"`);
  }
  if (summaryExcerpt) {
    textParts.push('', `AI Insights:\n${summaryExcerpt.slice(0, 2500)}`);
  }
  if (includeTranscript && transcriptPreview) {
    textParts.push('', `Transcript Excerpt:\n${transcriptPreview.slice(0, 1500)}`);
  }
  textParts.push(
    '',
    includeTranscript
      ? 'The full AI report (PDF) and bilingual transcript (.txt) are attached.'
      : 'The full AI report is attached as a PDF.'
  );

  const text = textParts.filter(Boolean).join('\n');

  const detailRows = [
    { label: 'Session', value: title },
    { label: 'AI Report', value: reportLabel },
  ];
  if (senderName) detailRows.push({ label: 'Shared by', value: senderName });
  if (orgName) detailRows.push({ label: 'Workspace', value: orgName });

  const noteBlock =
    personalNote && String(personalNote).trim()
      ? `<div style="margin-top:8px;margin-bottom:12px;padding:12px 16px;border-radius:10px;background:#eff6ff;border-left:4px solid #2563eb;font-size:14px;line-height:1.55;color:#1e293b;">
           <strong style="display:block;font-size:11px;text-transform:uppercase;letter-spacing:0.04em;color:#2563eb;margin-bottom:4px;">Note from ${escapeHtml(senderName || 'Sender')}</strong>
           ${nl2br(String(personalNote).trim().slice(0, 600))}
         </div>`
      : '';

  const insightsBlock = summaryExcerpt
    ? `<div style="margin-top:8px;padding:16px;border-radius:12px;background:#f8fafc;border:1px solid #e2e8f0;">
         <p style="margin:0 0 8px;font-size:12px;font-weight:600;letter-spacing:0.04em;text-transform:uppercase;color:#2563eb;">${escapeHtml(reportLabel)}</p>
         <div>${formatMarkdownPreviewHtml(summaryExcerpt.slice(0, 3000))}</div>
       </div>`
    : '';

  const transcriptBlock =
    includeTranscript && transcriptPreview
      ? `<div style="margin-top:12px;padding:16px;border-radius:12px;background:#f8fafc;border:1px solid #e2e8f0;">
           <p style="margin:0 0 8px;font-size:12px;font-weight:600;letter-spacing:0.04em;text-transform:uppercase;color:#64748b;">Bilingual Transcript Preview (Full .txt attached)</p>
           <div style="font-size:13px;line-height:1.6;color:#334155;font-family:ui-monospace,SFMono-Regular,Menlo,monospace;">${nl2br(transcriptPreview.slice(0, 1200))}</div>
         </div>`
      : '';

  const html = renderEmailLayout({
    preheader: `${reportLabel} for ${title} is attached.`,
    title: `${reportLabel}: ${title}`,
    introHtml: `<p style="margin:0;">${senderName ? `<strong>${escapeHtml(senderName)}</strong> shared the` : "Here's the"} <strong>${escapeHtml(reportLabel.toLowerCase())}</strong> for <strong>${escapeHtml(title)}</strong>${orgName ? ` (${escapeHtml(orgName)})` : ''}. ${includeTranscript ? 'The full PDF report and bilingual transcript are attached.' : 'The full report is attached as a PDF.'}</p>`,
    detailRows,
    secondaryHtml: `${noteBlock}${insightsBlock}${transcriptBlock}`,
    footerNote: 'Generated by Lalia — Live multilingual calls, meetings & AI insights.',
  });

  return { subject, text, html };
}

module.exports = { renderTranscriptReport };
