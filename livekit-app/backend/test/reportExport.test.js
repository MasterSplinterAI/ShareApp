const assert = require('node:assert/strict');
const test = require('node:test');
const { reportToMarkdown, reportToPdfBuffer } = require('../lib/reportExport');

const generatedAt = new Date('2026-11-13T19:12:50.000Z');
const report = { template_id: 'executive_summary', line_count: 2, content_markdown: 'Synthetic report.' };

for (const createdAt of [generatedAt.toISOString(), '2026-11-13 19:12:50', '2026-11-13T14:12:50-05:00']) {
  test(`report exports preserve the recorded time for ${createdAt}`, async () => {
    const details = { report: { ...report, created_at: createdAt }, meetingTitle: 'Synthetic meeting' };
    const expectedTime = generatedAt.toLocaleString('en-US', { dateStyle: 'medium', timeStyle: 'short' });
    assert.ok(reportToMarkdown(details).includes(`Generated by Lalia on ${expectedTime}`));
    const pdf = await reportToPdfBuffer(details);
    assert.equal(pdf.subarray(0, 5).toString(), '%PDF-');
  });
}
