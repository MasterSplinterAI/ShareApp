const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
require('./supportIsolation').prepareSupportTest();

test('Lalia keeps the original static article, serves cached edits offline, and honors unpublishing', async t => {
  const db = require('../db/v2Database');
  await db.initDatabase();
  const express = require('express');
  const { signOpsWebhookPayload } = require('@rhule/ops-sdk');
  const { freezeMarketingAuthority, startMarketingCache } = require('@rhule/marketing-core');
  const { consentDatabase } = require('../lib/consent');
  const { initializeMarketingAuthority, refreshMarketingProjection } = require('../lib/marketingAuthority');
  const { captureStaticBaseline, publicMarketingHandlers } = require('../lib/marketingPublicPages');
  const { getLaliaMarketingKit } = require('../lib/marketingKit');
  const kit = getLaliaMarketingKit();
  await kit.ensureSchema();
  await initializeMarketingAuthority();
  const slug = `cache-fixture-${db.uuid()}`;
  const post = await kit.store.createPost('lalia',{slug,title:'Original fixture',status:'published'});
  const row = await consentDatabase.get('SELECT * FROM mkt_posts WHERE id=?',[post.id]);
  const directory = fs.mkdtempSync(path.join(os.tmpdir(),'lalia-marketing-public-'));
  const originalFile = path.join(directory,'blog',slug,'index.html');
  fs.mkdirSync(path.dirname(originalFile),{recursive:true});
  fs.writeFileSync(originalFile,'<html><link rel="alternate" hreflang="es" href="/es/blog/fixture"><p>Original static edition</p></html>');
  fs.writeFileSync(path.join(directory,'sitemap.xml'),`<urlset><url><loc>https://lalia.cloud/blog/${slug}</loc></url><url><loc>https://lalia.cloud/es/blog/fixture</loc></url></urlset>`);
  process.env.MARKETING_STATIC_ROOT = directory;
  process.env.MARKETING_OPSHUB_ORIGIN = 'http://127.0.0.1:5395';
  process.env.MARKETING_OPSHUB_PEER_KEY = 'isolated-marketing-cache-signing-key';
  let snapshot = {version:1,businessId:'lalia',generation:2,revision:1,posts:[row],assets:[]};
  let offline = false, signatureValid = true;
  const peer = express();
  peer.get('/api/v1/marketing/published-projection',async (_req,res) => {
    if (offline) return res.sendStatus(503);
    const raw = JSON.stringify(snapshot);
    res.setHeader('X-Marketing-Signature', await signOpsWebhookPayload(raw,signatureValid ? process.env.MARKETING_OPSHUB_PEER_KEY : 'wrong-key'));
    res.type('json').send(raw);
  });
  const app = express();
  const pages = publicMarketingHandlers(kit);
  app.get('/blog/:slug',pages.blogPost);
  app.get('/sitemap.xml',pages.sitemap);
  const central = await new Promise(resolve => {const server=peer.listen(5395,'127.0.0.1',()=>resolve(server));});
  const publicSite = await new Promise(resolve => {const server=app.listen(5396,'127.0.0.1',()=>resolve(server));});
  t.after(async () => {
    await Promise.all([central,publicSite].map(server=>new Promise(resolve=>server.close(resolve))));
    await db.close();
    fs.rmSync(directory,{recursive:true,force:true});
  });
  const article = () => fetch(`http://127.0.0.1:5396/blog/${slug}`);
  await freezeMarketingAuthority(consentDatabase,'lalia',1);
  await captureStaticBaseline();
  await startMarketingCache(consentDatabase,'lalia',2);
  assert.equal(await refreshMarketingProjection(),true);
  assert.match(await (await article()).text(),/Original static edition/);
  snapshot = {...snapshot,revision:2,posts:[{...row,title:'Updated cached article'}]};
  signatureValid = false;
  await assert.rejects(refreshMarketingProjection(),/signature is invalid/);
  assert.match(await (await article()).text(),/Original static edition/);
  signatureValid = true;
  assert.equal(await refreshMarketingProjection(),true);
  offline = true;
  await assert.rejects(refreshMarketingProjection(),/projection is unavailable/);
  assert.match(await (await article()).text(),/Updated cached article/);
  offline = false;
  snapshot = {...snapshot,revision:3,posts:[]};
  assert.equal(await refreshMarketingProjection(),true);
  assert.equal((await article()).status,404);
  const sitemap = await (await fetch('http://127.0.0.1:5396/sitemap.xml')).text();
  assert.ok(!sitemap.includes(`/blog/${slug}`));
  assert.ok(sitemap.includes('/es/blog/fixture'));
});
